import puppeteer, { KnownDevices } from "puppeteer-core";
import create from "./create.mjs";
const b = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox"] });
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const p = await (await b.createBrowserContext()).newPage();
await p.emulate(KnownDevices["Pixel 5"]);
p.on("pageerror", e => console.log("pageerror", e.message));
await p.goto("http://localhost:5174/", { waitUntil: "load" });
await p.waitForSelector("form.boot-panel", { timeout: 60000 });
await create(p);
await sleep(2000);
await p.evaluate(() => { window.__moves = []; const ws = WebSocket.prototype.send; WebSocket.prototype.send = function (d) { try { const m = JSON.parse(d); if (m.type === "move") window.__moves.push([+m.x.toFixed(1), +m.z.toFixed(1)]); } catch {} return ws.call(this, d); }; });
const cdp = await p.createCDPSession();
await cdp.send("Emulation.setCPUThrottlingRate", { rate: Number(process.env.RATE ?? 4) });
console.log("layout", await p.evaluate(() => document.documentElement.dataset.uiLayout), "pad", !!(await p.$(".arcade-stick-pad")), "faces", (await p.$$(".arcade-face-btn")).length);
const pos = () => p.evaluate(() => { const m = window.__moves; return m.length + " moves, last " + JSON.stringify(m[m.length-1] ?? null); });
const fps = () => p.evaluate(() => new Promise(r => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 3000) requestAnimationFrame(f); else r((n / 3).toFixed(1)); }; requestAnimationFrame(f); }));
const tickMs = () => p.evaluate(() => new Promise(r => { const R = window.__stick.r; const o = R.tick.bind(R); let t = 0, n = 0; R.tick = (dt) => { const a = performance.now(); o(dt); t += performance.now() - a; n++; }; setTimeout(() => { R.tick = o; r((t / n).toFixed(1) + "ms/tick"); }, 3000); }));
console.log("tick", await tickMs());
console.log("fps no-atmo", await fps(), "tick", await tickMs());
console.log("fps idle (4x CPU)", await fps());
const pad = await (await p.$(".arcade-stick-pad")).boundingBox();
const cx = pad.x + pad.width / 2, cy = pad.y + pad.height / 2;
const before = await pos();
await p.touchscreen.touchStart(cx, cy); await p.touchscreen.touchMove(cx + 40, cy - 10);
const fpsMove = await fps();
await sleep(1000); await p.touchscreen.touchEnd();
console.log("joystick", before, "->", await pos(), "fps moving", fpsMove);
await p.screenshot({ path: "/workspace/ba-research/screens/m4-mobile-joystick.png" });
const b2 = await pos();
console.log("hit", await p.evaluate(() => [[200,260],[200,400],[100,500],[300,300]].map(([x,y]) => { const e = document.elementFromPoint(x,y); return x+","+y+":"+e?.tagName+"."+e?.className; }).join(" ")));
await p.touchscreen.tap(200, 260); await sleep(2500);
console.log("tap-to-move", b2, "->", await pos());
await p.screenshot({ path: "/workspace/ba-research/screens/m4-mobile.png" });
await b.close();
