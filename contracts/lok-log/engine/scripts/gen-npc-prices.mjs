#!/usr/bin/env node
/**
 * Maintain npc_price_data.rs + packages/items/src/npc-sell-units.generated.ts.
 *
 * Existing item ids keep their pinned unit price (pre-#222 table) so GoldSell
 * replay stays valid when craft fees / craftLevel change. New catalog ids are
 * priced with NPC_SELL_GOLD_BASIS=1000 (not recipe.gold).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "..");
const rustPath = join(root, "contracts/lok-log/engine/src/npc_price_data.rs");
const tsPath = join(root, "packages/items/src/npc-sell-units.generated.ts");
const catalog = JSON.parse(readFileSync(join(root, "packages/items/src/catalog.json"), "utf8"));

const NPC_SELL_GOLD_BASIS = 1000;

function computeUnit(i) {
  const craft = i.craftLevel ?? 1;
  switch (i.kind) {
    case "base":
      return 2;
    case "filler":
    case "bait":
      return 1;
    case "intermediate":
      return Math.max(5, 5 + Math.floor(craft / 10));
    case "consumable":
      return Math.max(3, Math.floor(NPC_SELL_GOLD_BASIS / 50));
    case "equipment":
      return Math.max(15, Math.floor(NPC_SELL_GOLD_BASIS / 20) + Math.floor(craft / 5));
    default:
      return Math.max(1, Math.floor(NPC_SELL_GOLD_BASIS / 25));
  }
}

function parsePinned(src) {
  const map = new Map();
  for (const m of src.matchAll(/\((\d+),\s*(\d+)\)/g)) {
    map.set(Number(m[1]), Number(m[2]));
  }
  return map;
}

const pinned = parsePinned(readFileSync(rustPath, "utf8"));
const rows = [];
for (const item of catalog) {
  const unit = pinned.has(item.id) ? pinned.get(item.id) : computeUnit(item);
  rows.push([item.id, unit]);
}
rows.sort((a, b) => a[0] - b[0]);

const rust = [
  "//! Pinned NPC sell units. Existing ids keep historical prices; new ids use",
  "//! NPC_SELL_GOLD_BASIS=1000 (not recipe.gold). Regenerate:",
  "//!   node contracts/lok-log/engine/scripts/gen-npc-prices.mjs",
  "",
  "/// Sorted (item_id, unit_gold) pairs from the item catalog.",
  "pub const NPC_SELL_UNITS: &[(u64, u64)] = &[",
  ...rows.map(([id, u]) => `    (${id}, ${u}),`),
  "];",
  "",
];
writeFileSync(rustPath, rust.join("\n"));

const ts = [
  "/* eslint-disable */",
  "/** Auto-generated by contracts/lok-log/engine/scripts/gen-npc-prices.mjs */",
  "export const NPC_SELL_UNITS: Readonly<Record<number, number>> = Object.freeze({",
  ...rows.map(([id, u]) => `  ${id}: ${u},`),
  "});",
  "",
];
writeFileSync(tsPath, ts.join("\n"));

const added = catalog.filter((i) => !pinned.has(i.id)).map((i) => i.id);
console.log("npc_price_data.rs:", rows.length, "items; new ids priced:", added.join(",") || "(none)");
