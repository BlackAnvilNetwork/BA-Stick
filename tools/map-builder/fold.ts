/**
 * Promote step: fold the live builder overlay (FOREST_BASIN_EDITS_PATH JSON)
 * into `packages/config/src/forest-basin-terrain.ts`, a 1 m grid the map
 * module reads. After this, bake (`pnpm --filter @bellgrave/stick-web zones`)
 * and reset the overlay (delete the edits file, restart the server).
 *
 *   tsx tools/map-builder/fold.ts [edits.json]
 * Grid bytes per cell: int16 LE height (cm), then one byte
 *   bits 0-1 biome (0 unpainted, 1 grass, 2 meadow, 3 mountain), bit 2 blocked, bit 3 forced walk.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
// Standalone on purpose: the config package imports the file this writes.
const BAZ_BIOME = { grass: 13, mountain: 14, meadow: 15 } as const; // keep in sync with zone-biomes.ts
const FOREST_BASIN_BOUNDS = { minX: -160, maxX: 160 } as const;

const ROOT = resolve(__dirname, "../..");
const src = process.argv[2] ?? resolve(ROOT, "tmp/forest-basin-edits.json");
const edits: Record<string, { heightCm?: number; biome?: number; blocked?: boolean }> = JSON.parse(readFileSync(src, "utf8"));
const { minX, maxX } = FOREST_BASIN_BOUNDS;
const W5 = Math.round((maxX - minX) / 0.5) + 1; // 641 overlay grid
const N = Math.round(maxX - minX) + 1; // 321 at 1 m
const BASE_CM = 200;
const buf = Buffer.alloc(N * N * 3);
let set = 0;
for (let j = 0; j < N; j++) {
  for (let i = 0; i < N; i++) {
    const e = edits[String(j * 2 * W5 + i * 2)];
    const o = (j * N + i) * 3;
    buf.writeInt16LE(e?.heightCm ?? BASE_CM, o);
    let b = 0;
    if (e?.biome === BAZ_BIOME.grass) b = 1;
    else if (e?.biome === BAZ_BIOME.meadow) b = 2;
    else if (e?.biome === BAZ_BIOME.mountain) b = 3;
    if (e?.blocked === true) b |= 4;
    if (e?.blocked === false) b |= 8;
    buf[o + 2] = b;
    if (e) set++;
  }
}
const b64 = buf.toString("base64");
const lines: string[] = [];
for (let k = 0; k < b64.length; k += 120) lines.push(`  "${b64.slice(k, k + 120)}"`);
writeFileSync(
  resolve(ROOT, "packages/config/src/forest-basin-terrain.ts"),
  `// Copyright (c) 2026 Black Anvil Network
// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by tools/map-builder/fold.ts from the map-builder overlay. Do not hand-edit:
// sculpt in game with the Map tab, then fold again.
/** Forest Basin terrain: ${N}x${N} cells at 1 m from (${minX},${minX}); int16 LE cm + flag byte per cell. */
export const FB_TERRAIN_N = ${N};
export const FB_TERRAIN_B64 =
${lines.join(" +\n")};
`,
);
console.log(`folded ${set}/${N * N} edited cells -> packages/config/src/forest-basin-terrain.ts (${(b64.length / 1024).toFixed(0)} KiB)`);
